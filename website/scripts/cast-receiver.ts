// Builds Kaeri's Cast receiver into public/cast/receiver/: bun scripts/cast-receiver.ts
//
// The page (index.html, receiver.css) and its strings (i18n/, from tools/i18n) are committed.
// This writes what is built from source or packages, which git ignores:
//   app.js           the receiver, from src/cast-receiver/
//   vendor/jassub/   JASSUB for typeset subtitles, as separate files with their notices
//   fonts/           Inter and Zen Kaku Gothic New, self-served, with fonts.css
// `bun run build` and `bun run dev` run it first.
import { execSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { BunPlugin } from 'bun';

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, '..');
const modules = join(site, 'node_modules');
const out = join(site, 'public/cast/receiver');

function build(): string {
	const sha = process.env.CF_PAGES_COMMIT_SHA ?? process.env.GITHUB_SHA;
	if (sha) return sha.slice(0, 9);
	try {
		return execSync('git rev-parse --short=9 HEAD', { cwd: site }).toString().trim();
	} catch {
		return 'dev';
	}
}

async function bundle(entry: string, file: string, plugins: BunPlugin[] = [], define: Record<string, string> = {}) {
	const result = await Bun.build({
		entrypoints: [entry],
		target: 'browser',
		format: 'esm',
		minify: false,
		plugins,
		define,
	});
	if (!result.success) {
		for (const log of result.logs) console.error(log);
		throw new Error(`bundling ${entry} failed`);
	}
	const [first] = result.outputs;
	writeFileSync(file, await first.text());
}

// rvfc-polyfill is GPL-3.0 and stays out: typeset subtitles run only where the browser has
// requestVideoFrameCallback itself (src/cast-receiver/typeset.ts checks).
const noPolyfill: BunPlugin = {
	name: 'no-rvfc-polyfill',
	setup(b) {
		b.onResolve({ filter: /^rvfc-polyfill$/ }, () => ({ path: 'rvfc-polyfill', namespace: 'empty' }));
		b.onLoad({ filter: /.*/, namespace: 'empty' }, () => ({ contents: '', loader: 'js' }));
	},
};

async function receiver() {
	await bundle(join(site, 'src/cast-receiver/main.ts'), join(out, 'app.js'), [], {
		__BUILD__: JSON.stringify(build()),
	});
}

async function jassub() {
	const pkg = join(modules, 'jassub');
	const dir = join(out, 'vendor/jassub');
	rmSync(dir, { recursive: true, force: true });
	mkdirSync(dir, { recursive: true });
	await bundle(join(pkg, 'dist/jassub.js'), join(dir, 'jassub.js'), [noPolyfill]);
	await bundle(join(pkg, 'dist/worker/worker.js'), join(dir, 'worker.js'));
	for (const f of ['wasm/jassub-worker.wasm', 'wasm/jassub-worker-modern.wasm', 'default.woff2'])
		copyFileSync(join(pkg, 'dist', f), join(dir, f.split('/').pop()!));
	copyFileSync(join(pkg, 'LICENSE'), join(dir, 'LICENSE'));
	copyFileSync(join(here, 'cast-receiver/NOTICE-jassub.txt'), join(dir, 'NOTICE.txt'));
}

/** Copies a Fontsource stylesheet's faces and their woff2 files, without the woff fallbacks. */
function faces(pkg: string, css: string, dir: string): string {
	const text = readFileSync(join(modules, pkg, css), 'utf8');
	return text.replace(/src: ([^;]+);/g, (_, src: string) => {
		const file = src.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
		if (!file) throw new Error(`${pkg}/${css}: a face without woff2`);
		copyFileSync(join(modules, pkg, 'files', file), join(dir, file));
		return `src: url(${file}) format('woff2');`;
	});
}

function fonts() {
	const dir = join(out, 'fonts');
	rmSync(dir, { recursive: true, force: true });
	mkdirSync(dir, { recursive: true });
	const css = [
		'/* Generated by scripts/cast-receiver.ts from Fontsource. SIL Open Font License 1.1; see NOTICE.txt. */',
		faces('@fontsource-variable/inter', 'wght.css', dir),
		faces('@fontsource/zen-kaku-gothic-new', '400.css', dir),
		faces('@fontsource/zen-kaku-gothic-new', '700.css', dir),
	].join('\n');
	writeFileSync(join(dir, 'fonts.css'), css);
	copyFileSync(join(modules, '@fontsource-variable/inter/LICENSE'), join(dir, 'LICENSE-inter.txt'));
	copyFileSync(join(modules, '@fontsource/zen-kaku-gothic-new/LICENSE'), join(dir, 'LICENSE-zen-kaku-gothic-new.txt'));
	copyFileSync(join(here, 'cast-receiver/NOTICE-fonts.txt'), join(dir, 'NOTICE.txt'));
}

mkdirSync(out, { recursive: true });
await receiver();
await jassub();
fonts();
console.log(`cast receiver built into ${out}`);
